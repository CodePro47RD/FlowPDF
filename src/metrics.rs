/// Ancho exacto en pt del texto en Helvetica (o Helvetica-Bold) a `size` pt, tal como lo escribe el motor
/// (WinAnsi). Un carácter sin glifo cuenta como una cifra.
pub fn helvetica_width(text: &str, size: f32, bold: bool) -> f32 {
    let tabla = if bold { &HELVETICA_BOLD } else { &HELVETICA };
    let milesimas: u32 = text
        .chars()
        .map(|c| match tabla[char_to_winansi(c) as usize] {
            0 => 556,
            w => w as u32,
        })
        .sum();
    milesimas as f32 * size / 1000.0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mide_con_los_anchos_de_adobe() {
        // "Wi" = 944 + 222 milésimas
        assert!((helvetica_width("Wi", 10.0, false) - 11.66).abs() < 0.001);
        // Las cifras miden lo mismo: los montos se alinean
        assert_eq!(helvetica_width("1,234.00", 9.0, false), helvetica_width("9,876.55", 9.0, false));
        // La negrita es más ancha
        assert!(helvetica_width("Pagado", 9.0, true) > helvetica_width("Pagado", 9.0, false));
        // Acentos de WinAnsi
        assert!((helvetica_width("ñ", 10.0, false) - 5.56).abs() < 0.001);
    }
}
